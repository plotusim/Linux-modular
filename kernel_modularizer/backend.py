def _short_id(module: str, symbol: str) -> str:
    readable = re.sub(r"[^A-Za-z0-9_]", "_", symbol)[:28]
    digest = hashlib.sha256(
        f"{module}\0{symbol}".encode("utf-8")
    ).hexdigest()[:10]
    return f"{readable}_{digest}"


def _runtime_id(module: str, symbol: str) -> str:
    """Return a compact, stable ID for one interface-table field.

    Fields do not enter kallsyms, but content-derived names keep generated
    headers deterministic when interfaces are reordered.
    """

    return hashlib.sha256(
        f"{module}\0{symbol}".encode("utf-8")
    ).hexdigest()[:16]


def _module_runtime_id(module: str) -> str:
    """Return the ID for the module's single exported operations table."""

    # Base32 carries 48 content-derived bits in ten identifier-safe bytes.
    # This keeps kallsyms/rodata strings compact without weakening the
    # collision bound used by the previous twelve-digit hexadecimal form.
    digest = hashlib.sha256(module.encode("utf-8")).digest()[:6]
    return base64.b32encode(digest).decode("ascii").rstrip("=").lower()


def _api_names(module: str, symbol: str) -> dict[str, str]:
    suffix = _module_runtime_id(module)
    return {
        "suffix": suffix,
        "type": f"mo{suffix}",
        "export": f"mx{suffix}",
        "field": f"f_{_runtime_id(module, symbol)}",
        "loader": f"mg{suffix}",
    }


def _dependency_api_names(module: str) -> dict[str, str]:
    suffix = _module_runtime_id(module)
    return {
        "type": f"mdt{suffix}",
        "export": f"md{suffix}",
        "pointer": f"mp{suffix}",
        "fill": f"mf{suffix}",
        "bind": f"mb{suffix}",
        "bind_lock": f"ml{suffix}",
        "bind_ready": f"mr{suffix}",
    }


def _dependency_pack_declaration(
    module_name: str,
    dependency_kinds: Mapping[str, str],
    resident_functions: Mapping[str, ExtractedFunction] | None = None,
    resident_globals: Mapping[str, ExtractedGlobal] | None = None,
    *,
    initialize_at_load: bool = False,
    bind_on_first_use: bool = False,
    module_storage: bool = False,
) -> str:
    names = _dependency_api_names(module_name)
    resident_functions = resident_functions or {}
    resident_globals = resident_globals or {}
    fields = []
    for symbol in sorted(dependency_kinds):
        function = resident_functions.get(symbol)
        if function is not None:
            fields.append(
                f"\t{function.return_type} (*{symbol})"
                f"({_parameter_types(function)});"
            )
        elif symbol in resident_globals:
            fields.append(
                "\t"
                + _global_pointer_declaration(
                    resident_globals[symbol].type, symbol
                )
                + ";"
            )
        else:
            fields.append(f"\ttypeof({symbol}) *{symbol};")
    tail = f"extern const struct {names['type']} {names['export']};"
    if initialize_at_load:
        tail = (
            (
                f"static struct {names['type']} {names['export']};\n"
                if module_storage
                else ""
            )
            + f"void {names['fill']}(struct {names['type']} *dependencies);"
        )
    elif bind_on_first_use:
        tail = (
            f"static struct {names['type']} {names['export']};"
            if module_storage
            else ""
        )
    return (
        "/* linux-modular: packed resident dependency ABI. */\n"
        f"struct {names['type']} {{\n"
        + "\n".join(fields)
        + "\n};\n"
        + tail
    )


def _dependency_pack_resident_export(
    module_name: str,
    dependency_kinds: Mapping[str, str],
    *,
    initialize_at_load: bool = False,
    bind_on_first_use: bool = False,
) -> str:
    names = _dependency_api_names(module_name)
    initializers = []
    for symbol, kind in sorted(dependency_kinds.items()):
        expression = symbol if kind == "function" else f"&{symbol}"
        initializers.append(f"\t.{symbol} = {expression},")
    if initialize_at_load:
        assignments = [
            f"\tdependencies->{symbol} = {expression};"
            for symbol, kind in sorted(dependency_kinds.items())
            for expression in (
                symbol if kind == "function" else f"&{symbol}",
            )
        ]
        return (
            f"void {names['fill']}(struct {names['type']} *dependencies)\n"
            "{\n"
            + "\n".join(assignments)
            + "\n}\n"
            + f"EXPORT_SYMBOL_GPL({names['fill']});"
        )
    if bind_on_first_use:
        assignments = [
            f"\tdependencies->{symbol} = {expression};"
            for symbol, kind in sorted(dependency_kinds.items())
            for expression in (
                symbol if kind == "function" else f"&{symbol}",
            )
        ]
        return (
            f"static void {names['fill']}"
            f"(struct {names['type']} *dependencies)\n"
            "{\n"
            + "\n".join(assignments)
            + "\n}"
        )
    return (
        # Keep the immutable dependency table out of the early .rodata
        # payload. Small tables placed immediately before an aligned rodata
        # island can otherwise consume a full permanent page even when the
        # extracted text saves several KiB. The kernel protects
        # .data..ro_after_init after boot, preserving the read-only contract.
        f"const struct {names['type']} {names['export']} "
        f"__ro_after_init = {{\n"
        + "\n".join(initializers)
        + "\n};\n"
        f"EXPORT_SYMBOL_GPL({names['export']});"
    )


def _dependency_reference_replacements(
    module_name: str,
    dependency_kinds: Mapping[str, str],
) -> dict[str, str]:
    pointer = _dependency_api_names(module_name)["pointer"]
    return {
        symbol: (
            f"{pointer}->{symbol}"
            if kind == "function"
            else f"(*{pointer}->{symbol})"
        )
        for symbol, kind in dependency_kinds.items()
    }


def _dependency_trampoline_name(module_name: str, symbol: str) -> str:
    return f"linux_mod_dep_{_short_id(module_name, symbol)}"


def _dependency_trampoline_signature(
    function: ExtractedFunction,
    module_name: str,
) -> str:
    parameters = (
        ", ".join(
            _ordinary_parameter_declaration(parameter)
            for parameter in function.parameters
        )
        if function.parameters
        else "void"
    )
    return (
        f"static {function.return_type} "
        f"{_dependency_trampoline_name(module_name, function.symbol)}"
        f"({parameters})"
    )


def _dependency_trampoline(
    function: ExtractedFunction,
    module_name: str,
) -> str:
    pointer = _dependency_api_names(module_name)["pointer"]
    arguments = ", ".join(function.forward_arguments)
    invocation = f"{pointer}->{function.symbol}({arguments})"
    if function.return_category == "void":
        body = f"\t{invocation};\n\treturn;"
    else:
        body = f"\treturn {invocation};"
    return (
        _dependency_trampoline_signature(function, module_name)
        + "\n{\n"
        + body
        + "\n}"
    )


def _parameter_types(function: ExtractedFunction) -> str:
    if not function.parameters:
        return "void"
    return ", ".join(parameter.type for parameter in function.parameters)


def _generate_interface_header(
    functions: Mapping[str, ExtractedFunction],
    interface_names: tuple[str, ...],
    module_name: str,
    *,
    bind_dependencies: bool = False,
) -> str:
    guard = (
        "_LINUX_MODULARIZER_"
        + _module_identifier(module_name).upper()
        + "_INTERFACE_H"
    )
    names = _api_names(module_name, interface_names[0])
    dependency_names = _dependency_api_names(module_name)
    lines = [
        "/* SPDX-License-Identifier: GPL-2.0 */",
        "/* Generated file: do not edit. */",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
    ]
    if bind_dependencies:
        lines.extend(
            [
                f"struct {dependency_names['type']};",
                "",
            ]
        )
    lines.append(f"struct {names['type']} {{")
    if bind_dependencies:
        lines.append(
            f"\tvoid (*b)(void (*fill)(struct "
            f"{dependency_names['type']} *));"
        )
    for symbol in interface_names:
        function = functions[symbol]
        names = _api_names(module_name, symbol)
        lines.append(
            f"\t{function.return_type} (*{names['field']})"
            f"({_parameter_types(function)});"
        )
    lines.extend(
        [
            "};",
            f"extern const struct {names['type']} {names['export']};",
            "",
            f"#endif /* {guard} */",
            "",
        ]
    )
    return "\n".join(lines)


def _runtime_block(
    function: ExtractedFunction,
    module_name: str,
    failure_expressions: Mapping[str, str],
    *,
    bind_dependencies: bool = False,
) -> str:
    names = _api_names(module_name, function.symbol)
    args = ", ".join(function.forward_arguments)
    used_names = {
        parameter.name
        for parameter in function.parameters
        if parameter.name
    }
    operations_name = _unique_local_name(
        "linux_modular_operations", used_names
    )
    used_names.add(operations_name)
    result_name = _unique_local_name("linux_modular_result", used_names)
    call = f"{operations_name}->{names['field']}({args})"
    failure = _failure_statement(function, failure_expressions)
    bind = ""
    if bind_dependencies:
        dependency_names = _dependency_api_names(module_name)
        bind = (
            f"\t{operations_name}->b({dependency_names['fill']});\n"
        )
    if function.return_category == "void":
        result_declaration = ""
        invocation = (
            f"\t{call};\n"
            f"\tsymbol_put({names['export']});\n"
            "\treturn;"
        )
    else:
        result_declaration = (
            f"\t{function.return_type} {result_name};\n"
        )
        invocation = (
            f"\t{result_name} = {call};\n"
            f"\tsymbol_put({names['export']});\n"
            f"\treturn {result_name};"
        )

    return f"""/* linux-modular interface: {function.symbol} */
{function.signature}
{{
\tconst struct {names['type']} *{operations_name};
{result_declaration}

\t{operations_name} = {names['loader']}();
\tif (!{operations_name})
\t\t{failure}
{bind.rstrip()}
{invocation}
}}"""


def _unique_local_name(base: str, used_names: set[str]) -> str:
    """Choose a deterministic wrapper local that cannot shadow a parameter."""

    candidate = base
    while candidate in used_names:
        candidate += "_"
    return candidate


def _failure_statement(
    function: ExtractedFunction,
    expressions: Mapping[str, str],
) -> str:
    custom = expressions.get(function.symbol)
    if custom is not None:
        if "\n" in custom or ";" in custom:
            raise GraphValidationError(
                f"{function.symbol}: failure expression must be one C "
                "expression without a semicolon"
            )
        return (
            "return;"
            if function.return_category == "void"
            else f"return ({custom});"
        )
    if function.return_category == "void":
        return "return;"
    if function.return_category == "pointer":
        return "return NULL;"
    if function.return_category == "integer":
        return "return -ENODEV;"
    raise GraphValidationError(
        f"{function.symbol}: return category {function.return_category!r} "
        "requires an explicit failure expression"
    )


def _runtime_includes(include_spelling: str) -> str:
    return "\n".join(
        [
            "#include <linux/cache.h>",
            "#include <linux/errno.h>",
            "#include <linux/interrupt.h>",
            "#include <linux/kernel.h>",
            "#include <linux/kmod.h>",
            "#include <linux/module.h>",
            f"#include <{include_spelling}>",
            "",
        ]
    )


def _runtime_loader(
    module_name: str,
    interface_symbol: str,
    autoload_name: str,
    *,
    bind_dependencies: bool = False,
) -> str:
    """Emit one non-inlined loader slow path per resident source file."""

    names = _api_names(module_name, interface_symbol)
    dependency_forward = ""
    if bind_dependencies:
        dependency_names = _dependency_api_names(module_name)
        dependency_forward = (
            f"static void {dependency_names['fill']}"
            f"(struct {dependency_names['type']} *dependencies);\n\n"
        )
    return dependency_forward + f"""/* linux-modular: shared lazy-loader boundary. */
static __attribute__((__noinline__)) const struct {names['type']}
*{names['loader']}(void)
{{
\tconst struct {names['type']} *operations;

\toperations = symbol_get({names['export']});
\tif (operations)
\t\treturn operations;
\tif (unlikely(system_state < SYSTEM_RUNNING ||
\t\t     in_interrupt() || irqs_disabled() || in_atomic()))
\t\treturn NULL;
\trequest_module("{autoload_name}");
\treturn symbol_get({names['export']});
}}

"""


def _partition_tracepoint_exports(
    symbols: tuple[str, ...],
) -> tuple[tuple[str, ...], tuple[str, ...]]:
    """Collapse tracepoint internals into the kernel's public export macro.

    Module-side tracepoint calls also reference architecture static-call
    symbols.  Exporting only ``__tracepoint_*`` and ``__traceiter_*`` thus
    compiles but fails MODPOST.  A complete audited pair is emitted through
    ``EXPORT_TRACEPOINT_SYMBOL_GPL`` so the kernel macro supplies that ABI.
    """

    symbol_set = set(symbols)
    tracepoints = tuple(
        sorted(
            symbol.removeprefix("__tracepoint_")
            for symbol in symbols
            if symbol.startswith("__tracepoint_")
            and "__traceiter_" + symbol.removeprefix("__tracepoint_")
            in symbol_set
        )
    )
    collapsed = {
        value
        for name in tracepoints
        for value in ("__tracepoint_" + name, "__traceiter_" + name)
    }
    ordinary = tuple(symbol for symbol in symbols if symbol not in collapsed)
    return ordinary, tracepoints


def _generate_resident_sources(
    extraction: SourceExtraction,
    functions: Mapping[str, ExtractedFunction],
    globals_by_name: Mapping[str, SourceEntity],
    interface_names: tuple[str, ...],
    policy: BackendPolicy,
    include_spelling: str,
    *,
    resident_exports: frozenset[str] = frozenset(),
    external_resident_exports: tuple[str, ...] = (),
    packed_dependency_kinds: Mapping[str, str] | None = None,
    resident_globals: frozenset[str] = frozenset(),
    duplicate_functions: frozenset[str] = frozenset(),
    resident_inline_proxies: frozenset[str] = frozenset(),
    preexisting_resident_exports: frozenset[str] = frozenset(),
) -> dict[str, str]:
    packed_dependency_kinds = packed_dependency_kinds or {}
    by_path: dict[str, list[tuple[int, int, str]]] = {}
    interfaces = set(interface_names)
    interface_entities_by_path: dict[str, list[ExtractedFunction]] = {}
    for interface_name in interface_names:
        interface = functions[interface_name]
        interface_entities_by_path.setdefault(
            interface.source_path, []
        ).append(interface)
    for function in functions.values():
        if function.symbol in duplicate_functions:
            continue
        if function.symbol in interfaces:
            replacement = _runtime_block(
                function,
                policy.module_name,
                policy.failure_expressions,
                bind_dependencies=(
                    policy.bind_packed_dependencies_on_first_use
                ),
            )
        elif function.symbol in resident_exports:
            if (
                function.symbol in packed_dependency_kinds
                or function.symbol in preexisting_resident_exports
            ):
                replacement = function.source
            else:
                replacement = (
                    _resident_export_source(function).rstrip()
                    + "\n"
                    + f"/* linux-modular: resident dependency for "
                    f"{policy.module_name}.ko */\n"
                    + f"EXPORT_SYMBOL_GPL({function.symbol});"
                )
        elif function.symbol in resident_inline_proxies:
            replacement = function.source
        else:
            replacement = (
                f"/* linux-modular: {function.symbol} moved to "
                f"{policy.module_name}.ko */"
            )
            for declaration in function.prior_declarations:
                by_path.setdefault(declaration.source_path, []).append(
                    (
                        declaration.start_offset,
                        declaration.end_offset,
                        "/* linux-modular: obsolete declaration for "
                        f"{function.symbol} */",
                    )
                )
        by_path.setdefault(function.source_path, []).append(
            (function.start_offset, function.end_offset, replacement)
        )
    for global_entity in globals_by_name.values():
        if global_entity.symbol in resident_globals:
            if (
                global_entity.symbol
                in policy.resident_ro_after_init_globals
            ):
                relative_name_end = (
                    global_entity.name_offset
                    - global_entity.start_offset
                    + global_entity.name_length
                )
                replacement = (
                    global_entity.source[:relative_name_end]
                    + " __ro_after_init"
                    + global_entity.source[relative_name_end:]
                )
                by_path.setdefault(global_entity.source_path, []).append(
                    (
                        global_entity.start_offset,
                        global_entity.end_offset,
                        replacement,
                    )
                )
            continue
        by_path.setdefault(global_entity.source_path, []).append(
            (
                global_entity.start_offset,
                global_entity.end_offset,
                f"/* linux-modular: global {global_entity.symbol} moved to "
                f"{policy.module_name}.ko */",
            )
        )

    includes_by_path: dict[str, list[int]] = {}
    for include in extraction.includes:
        path = include.source_path
        if path not in by_path:
            continue
        try:
            content = Path(path).read_text(encoding="utf-8")
        except OSError:
            continue
        if include.offset < len(content) and content[
            include.offset : include.offset + 1
        ] == "#":
            includes_by_path.setdefault(path, []).append(include.offset)

    output = {}
    export_anchor = (
        min(interface_entities_by_path)
        if interface_entities_by_path
        else min(by_path, default=None)
    )
    direct_external_exports = tuple(
        symbol
        for symbol in external_resident_exports
        if symbol not in packed_dependency_kinds
    )
    direct_external_exports, tracepoint_exports = (
        _partition_tracepoint_exports(direct_external_exports)
    )
    for path, replacements in by_path.items():
        content = Path(path).read_text(encoding="utf-8")
        insertion = _include_insertion_offset(
            content, includes_by_path.get(path, [])
        )
        runtime_includes = _runtime_includes(include_spelling)
        if path == export_anchor and tracepoint_exports:
            runtime_includes += "#include <linux/tracepoint.h>\n"
        interface_entities = interface_entities_by_path.get(path, [])
        runtime_loader = (
            _runtime_loader(
                policy.module_name,
                interface_entities[0].symbol,
                policy.autoload_alias or policy.module_name,
                bind_dependencies=(
                    policy.bind_packed_dependencies_on_first_use
                ),
            )
            if interface_entities
            else ""
        )
        support_exports = ""
        dependency_declaration = ""
        dependency_export = ""
        if path == export_anchor and packed_dependency_kinds:
            dependency_declaration = (
                _dependency_pack_declaration(
                    policy.module_name,
                    packed_dependency_kinds,
                    {
                        name: functions[name]
                        for name in resident_exports.union(
                            resident_inline_proxies
                        )
                        if name in packed_dependency_kinds
                    },
                    {
                        name: globals_by_name[name]
                        for name in resident_globals
                        if name in packed_dependency_kinds
                    },
                    initialize_at_load=(
                        policy.initialize_packed_dependencies_at_load
                    ),
                    bind_on_first_use=(
                        policy.bind_packed_dependencies_on_first_use
                    ),
                )
                + "\n\n"
            )
            dependency_export = _dependency_pack_resident_export(
                policy.module_name,
                packed_dependency_kinds,
                initialize_at_load=(
                    policy.initialize_packed_dependencies_at_load
                ),
                bind_on_first_use=(
                    policy.bind_packed_dependencies_on_first_use
                ),
            )
        if path == export_anchor and (
            direct_external_exports or tracepoint_exports
        ):
            support_exports = (
                "/* linux-modular: explicit GPL dependency surface. */\n"
                + "\n".join(
                    f"EXPORT_SYMBOL_GPL({symbol});"
                    for symbol in direct_external_exports
                )
                + (
                    "\n"
                    if direct_external_exports and tracepoint_exports
                    else ""
                )
                + "\n".join(
                    f"EXPORT_TRACEPOINT_SYMBOL_GPL({name});"
                    for name in tracepoint_exports
                )
                + "\n\n"
            )
        # Include offsets are measured against the original source.  Treat
        # the generated preamble as another source edit and apply every edit
        # from the end of the original file.  This remains correct when an
        # earlier moved helper shrinks the text before a late conditional
        # include (kernel/profile.c is one real example).
        edits = [
            *replacements,
            (insertion, insertion, runtime_includes + runtime_loader),
        ]
        _check_non_overlapping(path, edits)
        for start, end, replacement in sorted(edits, reverse=True):
            content = content[:start] + replacement + content[end:]
        late_support = "\n\n".join(
            block.rstrip()
            for block in (
                dependency_declaration,
                support_exports,
                dependency_export,
            )
            if block.strip()
        )
        if late_support:
            content = (
                content.rstrip()
                + "\n\n"
                + late_support
                + "\n"
            )
        output[path] = content
    return output


def _include_insertion_offset(content: str, original_offsets: list[int]) -> int:
    if not original_offsets:
        return 0
    last = max(original_offsets)
    newline = content.find("\n", last)
    return len(content) if newline < 0 else newline + 1


def _check_non_overlapping(
    path: str, replacements: list[tuple[int, int, str]]
) -> None:
    ordered = sorted(replacements)
    previous_end = -1
    for start, end, _ in ordered:
        if start < previous_end or end < start:
            raise GraphValidationError(
                f"overlapping AST ranges in {path}; extraction is unsafe"
            )
        previous_end = end


def _deduplicate_edits(
    edits: list[tuple[int, int, str]],
    *,
    path: str,
) -> list[tuple[int, int, str]]:
    """Collapse repeated AST references to one macro-argument token."""

    replacements_by_range: dict[tuple[int, int], set[str]] = {}
    for start, end, replacement in edits:
        replacements_by_range.setdefault((start, end), set()).add(
            replacement
        )
    conflicts = sorted(
        (start, end)
        for (start, end), replacements in replacements_by_range.items()
        if len(replacements) != 1
    )
    if conflicts:
        raise GraphValidationError(
            f"conflicting AST replacements in {path}: "
            + ", ".join(f"{start}:{end}" for start, end in conflicts)
        )
    return [
        (start, end, next(iter(replacements)))
        for (start, end), replacements in replacements_by_range.items()
    ]


def _has_prior_static_declaration(
    function: ExtractedFunction,
) -> bool:
    try:
        prefix = Path(function.source_path).read_text(
            encoding="utf-8"
        )[: function.start_offset]
    except OSError as error:
        raise GraphValidationError(
            f"cannot inspect declarations for {function.symbol}: {error}"
        ) from error
    declaration = re.compile(
        r"\bstatic\b[^;{}]*\b"
        + re.escape(function.name_spelling)
        + r"\s*\([^;{}]*\)\s*;",
        re.DOTALL,
    )
    return declaration.search(prefix) is not None


def _resident_export_source(
    function: ExtractedFunction,
) -> str:
    if function.storage != "static":
        return function.source
    relative_body = function.body_start_offset - function.start_offset
    signature = function.source[:relative_body]
    matches = list(re.finditer(r"\bstatic\s+", signature))
    if len(matches) != 1:
        raise GraphValidationError(
            f"{function.symbol}: cannot safely externalize static "
            "resident dependency"
        )
    match = matches[0]
    return (
        function.source[: match.start()]
        + function.source[match.end() :]
    )


def _rename_entity_source(
    entity: SourceEntity,
    rename: Mapping[str, str],
    dependency_replacements: Mapping[str, str] | None = None,
) -> str:
    dependency_replacements = dependency_replacements or {}
    if (
        isinstance(entity, ExtractedFunction)
        and entity.source_form == "syscall_define"
    ):
        replacement = rename.get(entity.symbol)
        if replacement is None:
            raise GraphValidationError(
                f"{entity.symbol}: syscall implementation has no rename"
            )
        return _syscall_module_implementation(
            entity,
            replacement,
            rename,
            dependency_replacements,
        )
    edits: list[tuple[int, int, str]] = []
    if entity.symbol in rename:
        relative = entity.name_offset - entity.start_offset
        edits.append(
            (relative, relative + entity.name_length, rename[entity.symbol])
        )
    for reference in entity.references:
        replacement = rename.get(reference.symbol)
        if replacement is not None and reference.kind != "function":
            replacement = None
        if replacement is None:
            replacement = dependency_replacements.get(reference.symbol)
        if replacement is None:
            continue
        relative = reference.offset - entity.start_offset
        edits.append((relative, relative + reference.length, replacement))
    edits = _deduplicate_edits(edits, path=entity.source_path)
    _check_non_overlapping(entity.source_path, edits)
    source = entity.source
    for start, end, replacement in sorted(edits, reverse=True):
        source = source[:start] + replacement + source[end:]
    return source


def _renamed_signature(
    function: ExtractedFunction, replacement: str
) -> str:
    if function.source_form == "syscall_define":
        return _ordinary_function_signature(function, replacement)
    relative_name = function.name_offset - function.start_offset
    relative_body = function.body_start_offset - function.start_offset
    signature = function.source[:relative_body].rstrip()
    if relative_name + function.name_length > len(signature):
        raise GraphValidationError(
            f"{function.symbol}: function name is outside AST signature"
        )
    return (
        signature[:relative_name]
        + replacement
        + signature[relative_name + function.name_length :]
    )


def _ordinary_parameter_declaration(parameter: Any) -> str:
    type_spelling = parameter.type
    pointer_marker = "(*)"
    if pointer_marker in type_spelling:
        return type_spelling.replace(
            pointer_marker,
            f"(*{parameter.name})",
            1,
        )
    return f"{type_spelling} {parameter.name}".strip()


def _global_pointer_declaration(type_spelling: str, name: str) -> str:
    """Declare a pointer to an extracted object without ``typeof(symbol)``.

    A source-local resident global is intentionally not declared in the
    generated module, so ``typeof(symbol)`` cannot describe its dependency
    table field there. Clang's type spelling is sufficient once the C
    declarator is adjusted for arrays and function-pointer objects.
    """

    spelling = type_spelling.strip()
    if "(*)" in spelling:
        return spelling.replace("(*)", f"(**{name})", 1)
    array = re.fullmatch(
        r"(.+?)(\s*(?:\[[^\[\]]*\]\s*)+)", spelling
    )
    if array is not None:
        return f"{array.group(1).rstrip()} (*{name}){array.group(2).strip()}"
    return f"{spelling} *{name}"


def _ordinary_function_signature(
    function: ExtractedFunction,
    replacement: str,
    *,
    preserve_static: bool = True,
) -> str:
    if function.has_unnamed_parameter:
        raise GraphValidationError(
            f"{function.symbol}: syscall parameter is unnamed"
        )
    parameters = (
        ", ".join(
            _ordinary_parameter_declaration(parameter)
            for parameter in function.parameters
        )
        if function.parameters
        else "void"
    )
    storage = (
        "static "
        if preserve_static and function.storage == "static"
        else ""
    )
    return (
        f"{storage}{function.return_type} {replacement}"
        f"({parameters})"
    )


def _syscall_module_implementation(
    function: ExtractedFunction,
    replacement: str,
    rename: Mapping[str, str],
    dependency_replacements: Mapping[str, str] | None = None,
) -> str:
    dependency_replacements = dependency_replacements or {}
    relative_start = (
        function.body_start_offset - function.start_offset
    )
    relative_end = function.body_end_offset - function.start_offset
    if (
        relative_start < 0
        or relative_end < relative_start
        or relative_end > len(function.source)
    ):
        raise GraphValidationError(
            f"{function.symbol}: syscall body is outside source range"
        )
    body = function.source[relative_start:relative_end]
    edits: list[tuple[int, int, str]] = []
    for reference in function.references:
        renamed = rename.get(reference.symbol)
        if renamed is not None and reference.kind != "function":
            renamed = None
        if renamed is None:
            renamed = dependency_replacements.get(reference.symbol)
        if renamed is None:
            continue
        if not (
            function.body_start_offset
            <= reference.offset
            < function.body_end_offset
        ):
            continue
        offset = reference.offset - function.body_start_offset
        edits.append(
            (offset, offset + reference.length, renamed)
        )
    edits = _deduplicate_edits(edits, path=function.source_path)
    _check_non_overlapping(function.source_path, edits)
    for start, end, renamed in sorted(edits, reverse=True):
        body = body[:start] + renamed + body[end:]
    return (
        _ordinary_function_signature(function, replacement)
        + "\n"
        + body
    )


def _module_operations_export(
    interface_names: tuple[str, ...],
    rename: Mapping[str, str],
    module_name: str,
    *,
    bind_dependencies: bool = False,
) -> str:
    """Expose all implementations through one typed operations table.

    The resident wrapper acquires the table with symbol_get(), which pins the
    owning module for the complete call. One exported symbol per module
    amortizes ksymtab, kallsyms, string and lookup costs across every
    interface while each typed field keeps the call ABI checked by C.
    """

    names = _api_names(module_name, interface_names[0])
    fields = [
        f"\t.{_api_names(module_name, symbol)['field']} = "
        f"{rename[symbol]},"
        for symbol in interface_names
    ]
    if bind_dependencies:
        fields.insert(
            0,
            f"\t.b = {_dependency_api_names(module_name)['bind']},",
        )
    return (
        f"const struct {names['type']} {names['export']} = {{\n"
        + "\n".join(fields)
        + "\n};\n"
        + f"EXPORT_SYMBOL_GPL({names['export']});"
    )


def _module_dependency_binder(module_name: str) -> str:
    """Bind a module-owned dependency table exactly once on first use."""

    names = _dependency_api_names(module_name)
    return f"""static DEFINE_MUTEX({names['bind_lock']});
static int {names['bind_ready']};

static void {names['bind']}(void (*fill)(struct {names['type']} *))
{{
\tif (likely(smp_load_acquire(&{names['bind_ready']})))
\t\treturn;
\tmutex_lock(&{names['bind_lock']});
\tif (!{names['bind_ready']}) {{
\t\tfill(&{names['export']});
\t\tsmp_store_release(&{names['bind_ready']}, 1);
\t}}
\tmutex_unlock(&{names['bind_lock']});
}}"""


def _source_identifiers(text: str) -> set[str]:
    return set(_C_SOURCE_IDENTIFIER.findall(text))


def _module_support_source(
    item: LocalDeclaration | MacroDefinition,
) -> str:
    """Render a source-local declaration as a standalone declaration.

    Clang's range for a record or enum embedded in a variable declaration
    ends at the closing brace (for example ``struct state { ... } value;``).
    The module needs only the tag declaration, but that slice is not valid C
    until it receives its own semicolon.
    """

    source = item.source.rstrip()
    if (
        isinstance(item, LocalDeclaration)
        and item.kind in {"record", "enum"}
        and source.endswith("}")
    ):
        return source + ";"
    return source


def _select_module_support(
    extraction: SourceExtraction,
    module_functions: Mapping[str, ExtractedFunction],
    resident_functions: Mapping[str, ExtractedFunction],
    globals_by_name: Mapping[str, SourceEntity],
) -> tuple[tuple[LocalDeclaration, ...], tuple[MacroDefinition, ...]]:
    """Select source-local types and macro definitions needed by a module.

    Clang's function range intentionally excludes file-scope typedefs, enum
    definitions and ``#define`` directives.  A function-only copy therefore
    stops compiling as soon as it uses a type or macro private to its original
    translation unit.  The extractor records those declarations and the
    preprocessor expansions; this fixed-point selection copies only support
    text reachable from the moved entities and packed resident signatures.
    """

    declarations_by_path: dict[str, list[LocalDeclaration]] = {}
    for declaration in extraction.declarations:
        declarations_by_path.setdefault(
            declaration.source_path, []
        ).append(declaration)
    macros_by_path_name: dict[
        tuple[str, str], list[MacroDefinition]
    ] = {}
    for definition in extraction.macro_definitions:
        macros_by_path_name.setdefault(
            (definition.source_path, definition.name), []
        ).append(definition)
    for values in macros_by_path_name.values():
        values.sort(key=lambda item: item.start_offset)

    needed_tokens: dict[str, set[str]] = {}
    macro_requests: list[tuple[str, int, str]] = []
    for entity in [*module_functions.values(), *globals_by_name.values()]:
        needed_tokens.setdefault(entity.source_path, set()).update(
            _source_identifiers(entity.source)
        )
        needed_tokens[entity.source_path].update(
            entity.dependencies.declarations
        )
        syntax_only_macros: set[str] = set()
        if (
            isinstance(entity, ExtractedFunction)
            and entity.source_form == "syscall_define"
        ):
            invocation = re.match(
                r"\s*([A-Za-z_][A-Za-z0-9_]*)\s*\(",
                entity.source,
            )
            if invocation is not None:
                # The backend emits syscall macro forms as ordinary module
                # functions. The outer SYSCALL_DEFINE* macro is therefore
                # syntax-only; body macros remain real support requests.
                syntax_only_macros.add(invocation.group(1))
        macro_requests.extend(
            (entity.source_path, entity.start_offset, name)
            for name in entity.macros
            if name not in syntax_only_macros
        )
    for function in resident_functions.values():
        signature_types = " ".join(
            [
                function.return_type,
                *(parameter.type for parameter in function.parameters),
            ]
        )
        needed_tokens.setdefault(function.source_path, set()).update(
            _source_identifiers(signature_types)
        )

    selected_declarations: dict[
        tuple[str, int, int], LocalDeclaration
    ] = {}
    changed = True
    while changed:
        changed = False
        for source_path, declarations in declarations_by_path.items():
            tokens = needed_tokens.get(source_path, set())
            for declaration in declarations:
                key = (
                    declaration.source_path,
                    declaration.start_offset,
                    declaration.end_offset,
                )
                if key in selected_declarations or not tokens.intersection(
                    declaration.identifiers
                ):
                    continue
                selected_declarations[key] = declaration
                new_tokens = _source_identifiers(declaration.source)
                if not new_tokens.issubset(tokens):
                    tokens.update(new_tokens)
                changed = True

    # If Clang reports both a typedef and its nested named record, retain the
    # outer declaration.  Copying overlapping ranges would define the tag
    # twice in the generated translation unit.
    declarations = []
    selected_values = list(selected_declarations.values())
    for declaration in selected_values:
        if any(
            other is not declaration
            and other.source_path == declaration.source_path
            and other.start_offset <= declaration.start_offset
            and other.end_offset >= declaration.end_offset
            and (
                other.start_offset < declaration.start_offset
                or other.end_offset > declaration.end_offset
            )
            for other in selected_values
        ):
            continue
        declarations.append(declaration)
    declarations.sort(
        key=lambda item: (
            item.source_path,
            item.start_offset,
            item.end_offset,
        )
    )

    # Tokens inside selected declarations may themselves expand source-local
    # macros.  Queue them at the declaration's lexical position, then follow
    # definitions transitively (for example FDS_BYTES -> FDS_LONGS).
    for declaration in declarations:
        for token in _source_identifiers(declaration.source):
            if (declaration.source_path, token) in macros_by_path_name:
                macro_requests.append(
                    (
                        declaration.source_path,
                        declaration.start_offset,
                        token,
                    )
                )

    selected_macros: dict[tuple[str, str], MacroDefinition] = {}
    request_index = 0
    while request_index < len(macro_requests):
        source_path, before_offset, name = macro_requests[request_index]
        request_index += 1
        definitions = [
            item
            for item in macros_by_path_name.get((source_path, name), ())
            if item.start_offset < before_offset
        ]
        if not definitions:
            continue
        definition = definitions[-1]
        key = (source_path, name)
        previous = selected_macros.get(key)
        if previous is not None:
            if previous.source != definition.source:
                raise GraphValidationError(
                    f"source-local macro {name!r} has multiple active "
                    "definitions in one generated module"
                )
            continue
        selected_macros[key] = definition
        for token in _source_identifiers(definition.source):
            if (source_path, token) in macros_by_path_name:
                macro_requests.append(
                    (source_path, definition.start_offset, token)
                )

    macros = sorted(
        selected_macros.values(),
        key=lambda item: (item.source_path, item.start_offset, item.name),
    )

    # Combining several original translation units is safe only when their
    # local support namespace does not conflict.  Reject ambiguity rather than
    # silently binding a function to the wrong tag or macro.
    declaration_owner: dict[str, LocalDeclaration] = {}
    for declaration in declarations:
        for identifier in declaration.identifiers:
            previous = declaration_owner.get(identifier)
            if (
                previous is not None
                and previous.source_path != declaration.source_path
                and previous.source != declaration.source
            ):
                raise GraphValidationError(
                    "conflicting source-local declaration identifier "
                    f"{identifier!r} across translation units"
                )
            declaration_owner[identifier] = declaration
    macro_owner: dict[str, MacroDefinition] = {}
    for definition in macros:
        previous = macro_owner.get(definition.name)
        if (
            previous is not None
            and previous.source_path != definition.source_path
            and previous.source != definition.source
        ):
            raise GraphValidationError(
                f"conflicting source-local macro {definition.name!r} "
                "across translation units"
            )
        macro_owner[definition.name] = definition

    return tuple(declarations), tuple(macros)


def _validate_interface_support_visibility(
    functions: Mapping[str, ExtractedFunction],
    interface_names: tuple[str, ...],
    support_declarations: tuple[LocalDeclaration, ...],
) -> None:
    """Reject a public lazy ABI that names a translation-unit-local type.

    Source-local declarations can safely precede implementations in the
    generated module. They cannot safely be copied into the generated public
    header: the resident translation unit includes that header before its own
    local declarations, while copying the declaration into the header would
    later redefine it. Keep this limitation explicit until the backend can
    synthesize an independently named wire type.
    """

    identifiers_by_path: dict[str, set[str]] = {}
    for declaration in support_declarations:
        identifiers_by_path.setdefault(
            declaration.source_path, set()
        ).update(declaration.identifiers)

    for name in interface_names:
        function = functions[name]
        signature_types = " ".join(
            [
                function.return_type,
                *(parameter.type for parameter in function.parameters),
            ]
        )
        hidden = sorted(
            _source_identifiers(signature_types).intersection(
                identifiers_by_path.get(function.source_path, set())
            )
        )
        if hidden:
            raise GraphValidationError(
                f"{name}: lazy interface ABI uses source-local type(s): "
                + ", ".join(hidden)
            )


def _generate_module_source(
    extraction: SourceExtraction,
    functions: Mapping[str, ExtractedFunction],
    resident_functions: Mapping[str, ExtractedFunction],
    globals_by_name: Mapping[str, SourceEntity],
    interface_names: tuple[str, ...],
    rename: Mapping[str, str],
    policy: BackendPolicy,
    include_spelling: str,
    *,
    packed_dependency_kinds: Mapping[str, str] | None = None,
    resident_globals: Mapping[str, ExtractedGlobal] | None = None,
    packed_initializer_trampolines: Mapping[
        str, ExtractedFunction
    ]
    | None = None,
    support_declarations: tuple[LocalDeclaration, ...] = (),
    support_macros: tuple[MacroDefinition, ...] = (),
    include_overrides: Mapping[str, str] | None = None,
) -> str:
    packed_dependency_kinds = packed_dependency_kinds or {}
    resident_globals = resident_globals or {}
    packed_initializer_trampolines = (
        packed_initializer_trampolines or {}
    )
    include_overrides = include_overrides or {}
    includes = []
    seen_includes = set()
    entity_paths = {
        entity.source_path
        for entity in [
            *globals_by_name.values(),
            *resident_globals.values(),
            *functions.values(),
            *resident_functions.values(),
        ]
    }
    for include in extraction.includes:
        if include.source_path not in entity_paths:
            continue
        directive = include_overrides.get(
            str(Path(include.resolved).resolve()),
            _module_include_directive(include, policy.kernel_root),
        )
        if directive not in seen_includes:
            includes.append(directive)
            seen_includes.add(directive)
    includes.extend(
        [
            "#include <linux/init.h>",
            "#include <linux/module.h>",
            f"#include <{include_spelling}>",
        ]
    )
    if policy.bind_packed_dependencies_on_first_use:
        includes.append("#include <linux/mutex.h>")
    dependency_declaration = ""
    dependency_pointer = ""
    dependency_replacements: Mapping[str, str] = {}
    if packed_dependency_kinds:
        dependency_names = _dependency_api_names(policy.module_name)
        dependency_declaration = _dependency_pack_declaration(
            policy.module_name,
            packed_dependency_kinds,
            {
                name: function
                for name, function in resident_functions.items()
                if name in packed_dependency_kinds
            },
            {
                name: global_value
                for name, global_value in resident_globals.items()
                if name in packed_dependency_kinds
            },
            initialize_at_load=(
                policy.initialize_packed_dependencies_at_load
            ),
            bind_on_first_use=(
                policy.bind_packed_dependencies_on_first_use
            ),
            module_storage=(
                policy.initialize_packed_dependencies_at_load
                or policy.bind_packed_dependencies_on_first_use
            ),
        )
        dependency_pointer = (
            f"#define {dependency_names['pointer']} "
            f"(&{dependency_names['export']})"
        )
        dependency_replacements = _dependency_reference_replacements(
            policy.module_name,
            packed_dependency_kinds,
        )
    initializer_dependency_replacements = dict(
        dependency_replacements
    )
    initializer_dependency_replacements.update(
        {
            symbol: _dependency_trampoline_name(
                policy.module_name, symbol
            )
            for symbol in packed_initializer_trampolines
        }
    )
    module_defines = []
    if policy.module_defines:
        module_defines.append(
            "/* linux-modular: explicit source-local constants. */"
        )
        for name, expression in sorted(policy.module_defines.items()):
            guard = name.split("(", 1)[0]
            module_defines.extend(
                [
                    f"#ifndef {guard}",
                    f"#define {name} {expression}",
                    "#endif",
                ]
            )

    early_support_items = sorted(
        (
            item
            for item in support_macros
            if item.name in _EARLY_SUPPORT_MACROS
        ),
        key=lambda item: (
            item.source_path,
            item.start_offset,
            item.end_offset,
        ),
    )
    early_support_source = "\n\n".join(
        item.source.rstrip() for item in early_support_items
    )
    support_items = sorted(
        [*support_declarations, *support_macros],
        key=lambda item: (
            item.source_path,
            item.start_offset,
            item.end_offset,
        ),
    )
    support_items = [
        item
        for item in support_items
        if not (
            isinstance(item, MacroDefinition)
            and item.name in _EARLY_SUPPORT_MACROS
        )
    ]
    support_source = "\n\n".join(
        _module_support_source(item) for item in support_items
    )

    entities: list[SourceEntity] = [
        *globals_by_name.values(),
        *functions.values(),
    ]
    entities.sort(key=lambda item: (item.source_path, item.start_offset))
    implementations = [
        _rename_entity_source(
            entity,
            rename,
            (
                dependency_replacements
                if isinstance(entity, ExtractedFunction)
                else initializer_dependency_replacements
            ),
        )
        for entity in entities
    ]
    prototypes = [
        _renamed_signature(function, rename[function.symbol]) + ";"
        for function in functions.values()
    ]
    prototypes.extend(
        _ordinary_function_signature(
            function,
            function.name_spelling,
            preserve_static=False,
        )
        + ";"
        for function in resident_functions.values()
    )
    prototypes.extend(
        _dependency_trampoline_signature(
            function, policy.module_name
        )
        + ";"
        for function in packed_initializer_trampolines.values()
    )

    dependency_trampolines = [
        _dependency_trampoline(function, policy.module_name)
        for function in packed_initializer_trampolines.values()
    ]

    dependency_binder = (
        _module_dependency_binder(policy.module_name)
        if policy.bind_packed_dependencies_on_first_use
        else ""
    )
    operations_export = _module_operations_export(
        interface_names,
        rename,
        policy.module_name,
        bind_dependencies=(
            policy.bind_packed_dependencies_on_first_use
        ),
    )
    init_body = "\treturn 0;"
    if (
        packed_dependency_kinds
        and policy.initialize_packed_dependencies_at_load
    ):
        dependency_names = _dependency_api_names(policy.module_name)
        init_body = (
            f"\t{dependency_names['fill']}"
            f"(&{dependency_names['export']});\n"
            "\treturn 0;"
        )
    init_function = f"""static int __init linux_modularizer_init(void)
{{
{init_body}
}}"""
    exit_function = f"""static void __exit linux_modularizer_exit(void)
{{
}}"""
    module_alias = (
        f'MODULE_ALIAS("{_c_string(policy.autoload_alias)}");\n'
        if policy.autoload_alias
        else ""
    )

    return (
        "/* SPDX-License-Identifier: GPL-2.0 */\n"
        "/* Generated file: exact AST-selected source plus module lifecycle. */\n"
        + early_support_source
        + ("\n\n" if early_support_source else "")
        + "\n".join(includes)
        + "\n\n"
        + support_source
        + ("\n\n" if support_source else "")
        + dependency_declaration
        + ("\n" if dependency_declaration else "")
        + dependency_pointer
        + ("\n\n" if dependency_pointer else "")
        + "\n".join(module_defines)
        + ("\n\n" if module_defines else "")
        + "\n".join(prototypes)
        + "\n\n"
        + "\n\n".join(implementations)
        + ("\n\n" if dependency_trampolines else "")
        + "\n\n".join(dependency_trampolines)
        + ("\n\n" if dependency_binder else "")
        + dependency_binder
        + "\n\n"
        + operations_export
        + "\n\n"
        + init_function
        + "\n\n"
        + exit_function
        + "\n\nmodule_init(linux_modularizer_init);\n"
        + "module_exit(linux_modularizer_exit);\n"
        + f'MODULE_LICENSE("{policy.license}");\n'
        + f'MODULE_DESCRIPTION("{_c_string(policy.description)}");\n'
        + module_alias
    )


def _c_string(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ")


def _is_static_inline(function: ExtractedFunction) -> bool:
    return function.storage == "static" and bool(
        set(function.attributes).intersection(
            {"inline", "gnu_inline", "always_inline"}
        )
        or set(function.macros).intersection({"inline", "__always_inline"})
    )


def _module_include_directive(include: Any, kernel_root: str | None) -> str:
    """Make source-local quoted includes unambiguous in the module path.

    All generated modules share one Kbuild directory, so accumulated ``-I``
    flags can otherwise resolve generic names such as ``internal.h`` to the
    wrong subsystem.  A kernel-relative path from the generated source keeps
    the bundle relocatable and preserves the extractor's resolved header.
    """

    if include.angled or kernel_root is None:
        return include.directive
    root = Path(kernel_root).resolve()
    resolved = Path(include.resolved).resolve()
    try:
        relative = resolved.relative_to(root).as_posix()
    except ValueError:
        return include.directive
    written = posixpath.relpath(relative, "kernel/linux_modularizer")
    return f'#include "{written}"'


def _snapshot_external_quoted_headers(
    extraction: SourceExtraction,
    entities: list[SourceEntity],
    policy: BackendPolicy,
    module_object: str,
) -> tuple[dict[str, str], dict[str, str], list[dict[str, str]]]:
    """Copy build-generated quoted headers into the generated bundle.

    Out-of-tree kernel builds resolve some quoted headers from ``objtree``.
    A generated module lives in another Kbuild directory and cannot reuse the
    original relative lookup.  Snapshotting the exact header seen by Clang
    makes the bundle reproducible and avoids embedding a build-machine path.
    Source-tree headers continue to use kernel-relative include directives.
    """

    if policy.kernel_root is None:
        return {}, {}, []
    root = Path(policy.kernel_root).resolve()
    entity_paths = {entity.source_path for entity in entities}
    relevant = [
        include
        for include in extraction.includes
        if not include.angled and include.source_path in entity_paths
    ]
    overrides: dict[str, str] = {}
    files: dict[str, str] = {}
    records: list[dict[str, str]] = []
    external_search_directories: set[Path] = set()
    source_header_seeds: list[Path] = []
    external_seeds: list[tuple[Path, str]] = []
    for include in relevant:
        resolved = Path(include.resolved).resolve()
        try:
            resolved.relative_to(root)
            source_header_seeds.append(resolved)
        except ValueError:
            external_search_directories.add(resolved.parent)
            external_seeds.append((resolved, include.written))

    quoted_include = re.compile(
        r'^\s*#\s*include\s*"([^"]+)"', flags=re.MULTILINE
    )
    visited_source_headers: set[Path] = set()
    snapshotted_paths: dict[Path, str] = {}

    def safe_private_path(written: str, source: Path) -> Path:
        relative = Path(written)
        if (
            relative.is_absolute()
            or ".." in relative.parts
            or not relative.parts
            or any(
                not _HEADER_FILE_COMPONENT.fullmatch(part)
                for part in relative.parts
            )
        ):
            relative = Path(source.name)
        return relative

    def read_header(path: Path) -> str:
        if not path.is_file():
            raise GraphValidationError(
                "quoted include resolved outside kernel_root but is missing: "
                f"{path}"
            )
        try:
            return path.read_text(encoding="utf-8")
        except (OSError, UnicodeError) as error:
            raise GraphValidationError(
                f"cannot snapshot generated header {path}: {error}"
            ) from error

    def external_match(written: str) -> Path | None:
        matches = sorted(
            {
                (directory / written).resolve()
                for directory in external_search_directories
                if (directory / written).is_file()
            }
        )
        if not matches:
            return None
        digests = {_sha256_text(read_header(path)) for path in matches}
        if len(digests) != 1:
            raise GraphValidationError(
                "ambiguous build-generated quoted include "
                f"{written!r}: " + ", ".join(str(path) for path in matches)
            )
        return matches[0]

    def snapshot(path: Path, private_path: Path) -> None:
        path = path.resolve()
        previous = snapshotted_paths.get(path)
        if previous is not None:
            return
        content = read_header(path)
        digest = _sha256_text(content)
        relative = (
            "include/linux/linux_modularizer/generated/"
            f"{module_object}/{private_path.as_posix()}"
        )
        previous_content = files.get(relative)
        if previous_content is not None and previous_content != content:
            raise GraphValidationError(
                "generated quoted-header path collision at "
                f"{relative}: {path}"
            )
        snapshotted_paths[path] = relative
        spelling = relative.removeprefix("include/")
        overrides[str(path)] = f"#include <{spelling}>"
        files[relative] = content
        records.append(
            {
                "source_path": str(path),
                "bundle_path": relative,
                "sha256": digest,
            }
        )
        for written in quoted_include.findall(content):
            child = (path.parent / written).resolve()
            child_private = private_path.parent / safe_private_path(
                written, child
            )
            if child.is_file():
                try:
                    child.relative_to(root)
                except ValueError:
                    snapshot(child, child_private)
                continue
            match = external_match(written)
            if match is None:
                raise GraphValidationError(
                    f"cannot resolve nested quoted include {written!r} "
                    f"from generated header {path}"
                )
            snapshot(match, child_private)

    def scan_source_header(path: Path) -> None:
        path = path.resolve()
        if path in visited_source_headers or not path.is_file():
            return
        visited_source_headers.add(path)
        content = read_header(path)
        for written in quoted_include.findall(content):
            child = (path.parent / written).resolve()
            if child.is_file():
                try:
                    child.relative_to(root)
                except ValueError:
                    snapshot(child, safe_private_path(written, child))
                else:
                    scan_source_header(child)
                continue
            match = external_match(written)
            if match is not None:
                snapshot(match, safe_private_path(written, match))

    for resolved, written in external_seeds:
        snapshot(resolved, safe_private_path(written, resolved))
    for resolved in source_header_seeds:
        scan_source_header(resolved)
    return overrides, files, sorted(
        records, key=lambda record: record["bundle_path"]
    )


def _source_directories(
    entities: list[SourceEntity], kernel_root: str | None
) -> list[str]:
    if kernel_root is None:
        return []
    root = Path(kernel_root).resolve()
    directories = set()
    for entity in entities:
        try:
            relative = Path(entity.source_path).resolve().relative_to(root)
        except ValueError as error:
            raise GraphValidationError(
                f"source {entity.source_path} is outside kernel_root {root}"
            ) from error
        directories.add(relative.parent.as_posix())
    return sorted(directories)


def _resident_relative_path(
    source_path: str, kernel_root: str | None
) -> str:
    source = Path(source_path).resolve()
    if kernel_root is not None:
        root = Path(kernel_root).resolve()
        try:
            return source.relative_to(root).as_posix()
        except ValueError as error:
            raise GraphValidationError(
                f"source {source} is outside kernel_root {root}"
            ) from error
    digest = hashlib.sha256(str(source).encode("utf-8")).hexdigest()[:12]
    return f"{digest}/{source.name}"


def _sha256_text(content: str) -> str:
    return hashlib.sha256(content.encode("utf-8")).hexdigest()


def _bundle_manifest(
    files: Mapping[str, str],
    replacements: Mapping[str, str],
    policy: BackendPolicy,
    module_object: str,
    config_symbol: str,
    *,
    packed_dependency_kinds: Mapping[str, str] | None = None,
    packed_initializer_trampolines: Mapping[
        str, ExtractedFunction
    ]
    | None = None,
    preexisting_resident_exports: set[str] | None = None,
    resident_globals: set[str] | None = None,
    support_declarations: tuple[LocalDeclaration, ...] = (),
    support_macros: tuple[MacroDefinition, ...] = (),
    snapshotted_headers: list[dict[str, str]] | None = None,
) -> dict[str, Any]:
    packed_dependency_kinds = packed_dependency_kinds or {}
    packed_initializer_trampolines = (
        packed_initializer_trampolines or {}
    )
    preexisting_resident_exports = preexisting_resident_exports or set()
    resident_globals = resident_globals or set()
    snapshotted_headers = snapshotted_headers or []
    direct_external_exports = tuple(
        symbol
        for symbol in policy.external_resident_exports
        if symbol not in packed_dependency_kinds
    )
    direct_external_exports, tracepoint_exports = (
        _partition_tracepoint_exports(direct_external_exports)
    )
    resident = []
    for source_path, generated in sorted(replacements.items()):
        source = Path(source_path).resolve()
        try:
            original = source.read_text(encoding="utf-8")
        except OSError as error:
            raise GraphValidationError(
                f"cannot hash resident source {source}: {error}"
            ) from error
        relative = _resident_relative_path(str(source), policy.kernel_root)
        resident.append(
            {
                "source_path": str(source),
                "kernel_path": (
                    relative if policy.kernel_root is not None else None
                ),
                "bundle_path": f"resident/{relative}",
                "original_sha256": _sha256_text(original),
                "generated_sha256": _sha256_text(generated),
            }
        )
    return {
        "schema_version": BACKEND_SCHEMA_VERSION,
        "module_name": policy.module_name,
        "module_object": module_object,
        "config_symbol": config_symbol,
        "resident_exports": list(policy.resident_exports),
        "preexisting_resident_exports": sorted(
            preexisting_resident_exports
        ),
        "external_resident_exports": list(
            policy.external_resident_exports
        ),
        "resident_inline_proxies": list(
            policy.resident_inline_proxies
        ),
        "resident_globals": sorted(resident_globals),
        "pack_resident_dependencies": (
            policy.pack_resident_dependencies
        ),
        "initialize_packed_dependencies_at_load": (
            policy.initialize_packed_dependencies_at_load
        ),
        "bind_packed_dependencies_on_first_use": (
            policy.bind_packed_dependencies_on_first_use
        ),
        "packed_dependency_storage": (
            "module_first_use_initialized"
            if policy.bind_packed_dependencies_on_first_use
            else (
                "module_load_initialized"
                if policy.initialize_packed_dependencies_at_load
                else "resident_ro_after_init"
            )
        ),
        "forced_direct_resident_dependencies": list(
            policy.direct_resident_dependencies
        ),
        "packed_resident_exports": sorted(
            symbol
            for symbol in policy.resident_exports
            if symbol in packed_dependency_kinds
        ),
        "packed_external_resident_exports": sorted(
            symbol
            for symbol in policy.external_resident_exports
            if symbol in packed_dependency_kinds
        ),
        "packed_resident_inline_proxies": sorted(
            symbol
            for symbol in policy.resident_inline_proxies
            if symbol in packed_dependency_kinds
        ),
        "packed_initializer_trampolines": sorted(
            packed_initializer_trampolines
        ),
        "direct_resident_exports": [
            symbol
            for symbol in policy.resident_exports
            if symbol not in packed_dependency_kinds
        ],
        "direct_external_resident_exports": [
            *direct_external_exports,
        ],
        "tracepoint_resident_exports": list(tracepoint_exports),
        "resident_dependency_export_count": (
            (
                1
                if packed_dependency_kinds
                and not policy.bind_packed_dependencies_on_first_use
                else 0
            )
            + sum(
                symbol not in packed_dependency_kinds
                for symbol in policy.resident_exports
            )
            + len(direct_external_exports)
            # With inline static calls, this macro exports the tracepoint,
            # iterator, static-call key and trampoline.
            + 4 * len(tracepoint_exports)
        ),
        "duplicate_functions": list(policy.duplicate_functions),
        "module_defines": dict(sorted(policy.module_defines.items())),
        "resident_ro_after_init_globals": list(
            policy.resident_ro_after_init_globals
        ),
        "autoload_alias": policy.autoload_alias,
        "source_local_support": {
            "declarations": [
                {
                    "kind": declaration.kind,
                    "name": declaration.name,
                    "source_path": declaration.source_path,
                    "start_line": declaration.start_line,
                }
                for declaration in support_declarations
            ],
            "macros": [
                {
                    "name": definition.name,
                    "source_path": definition.source_path,
                }
                for definition in support_macros
            ],
        },
        "snapshotted_generated_headers": snapshotted_headers,
        "kernel_root": (
            str(Path(policy.kernel_root).resolve())
            if policy.kernel_root is not None
            else None
        ),
        "resident_replacements": resident,
        "generated_files": [
            {
                "path": path,
                "sha256": _sha256_text(content),
            }
            for path, content in sorted(files.items())
            if not path.startswith("resident/")
        ],
    }
