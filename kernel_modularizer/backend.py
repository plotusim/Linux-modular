BACKEND_SCHEMA_VERSION = 1
_C_IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
_C_MACRO_DECLARATOR = re.compile(
    r"^[A-Za-z_][A-Za-z0-9_]*"
    r"(?:\((?:[A-Za-z_][A-Za-z0-9_]*"
    r"(?:,\s*[A-Za-z_][A-Za-z0-9_]*)*)?\))?$"
)
_C_DEFINE_EXPRESSION = re.compile(
    r"^[A-Za-z0-9_ \t()+\-*/%<>&|^~?:.]+$"
)
_C_SOURCE_IDENTIFIER = re.compile(r"\b[A-Za-z_][A-Za-z0-9_]*\b")
_MODULE_ALIAS = re.compile(r"^[A-Za-z0-9_.:+-]{1,64}$")
_HEADER_FILE_COMPONENT = re.compile(r"^[A-Za-z0-9_.-]+$")
_EARLY_SUPPORT_MACROS = frozenset({"pr_fmt"})
_UNSAFE_FUNCTION_ATTRIBUTES = frozenset(
    {
        "always_inline",
        "section",
        "naked",
        "interrupt",
        "no_instrument_function",
        "constructor",
        "destructor",
        "retain",
        "used",
        "weak",
    }
)
_UNSAFE_FUNCTION_MACROS = frozenset(
    {
        "__always_inline",
        "__init",
        "__exit",
        "__meminit",
        "__memexit",
        "__cpuinit",
        "__cpuexit",
        "__head",
        "__irq_entry",
        "__naked",
        "noinstr",
        "notrace",
        "NOKPROBE_SYMBOL",
    }
)
_UNSAFE_GLOBAL_ATTRIBUTES = frozenset(
    {
        "section",
        "cleanup",
        "alias",
        "weak",
        "retain",
        "used",
        "tls_model",
    }
)
_UNSAFE_GLOBAL_MACROS = frozenset(
    {
        "__initdata",
        "__initconst",
        "__exitdata",
        "__meminitdata",
        "__memexitdata",
        "__ro_after_init",
        "__read_mostly",
    }
)


@dataclass(frozen=True)
class BackendPolicy:
    module_name: str
    interfaces: tuple[str, ...]
    failure_expressions: Mapping[str, str] = field(default_factory=dict)
    resident_exports: tuple[str, ...] = ()
    external_resident_exports: tuple[str, ...] = ()
    resident_inline_proxies: tuple[str, ...] = ()
    pack_resident_dependencies: bool = False
    initialize_packed_dependencies_at_load: bool = False
    bind_packed_dependencies_on_first_use: bool = False
    direct_resident_dependencies: tuple[str, ...] = ()
    duplicate_functions: tuple[str, ...] = ()
    module_defines: Mapping[str, str] = field(default_factory=dict)
    resident_ro_after_init_globals: tuple[str, ...] = ()
    autoload_alias: str | None = None
    license: str = "GPL"
    description: str = "Function-level kernel module generated by Linux-modular"
    kernel_root: str | None = None


@dataclass(frozen=True)
class GeneratedBundle:
    files: Mapping[str, str]
    source_replacements: Mapping[str, str]
    config_symbol: str
    module_object: str
    manifest: Mapping[str, Any]

    def write(self, output_directory: str | Path) -> None:
        root = Path(output_directory)
        for relative, content in sorted(self.files.items()):
            path = Path(relative)
            if path.is_absolute() or ".." in path.parts:
                raise GraphValidationError(
                    f"unsafe generated bundle path: {relative!r}"
                )
            write_text_atomic(root / path, content)
        write_json_atomic(root / "bundle.json", self.manifest)


def generate_module_bundle(
    extraction: SourceExtraction,
    policy: BackendPolicy,
) -> GeneratedBundle:
    extraction.verify_sources()
    module_object = _module_identifier(policy.module_name)
    if not policy.interfaces:
        raise GraphValidationError(
            "backend requires at least one resident interface"
        )

    functions = _unique_symbols(extraction.functions, "function")
    globals_by_name = _unique_symbols(extraction.globals, "global")
    interface_names = tuple(dict.fromkeys(policy.interfaces))
    resident_export_names = tuple(
        dict.fromkeys(policy.resident_exports)
    )
    external_resident_export_names = tuple(
        dict.fromkeys(policy.external_resident_exports)
    )
    resident_inline_proxy_names = tuple(
        dict.fromkeys(policy.resident_inline_proxies)
    )
    dependency_resident_global_names = frozenset(
        set(external_resident_export_names).intersection(globals_by_name)
    )
    resident_global_names = frozenset(
        set(dependency_resident_global_names)
        | set(policy.resident_ro_after_init_globals)
    )
    moved_globals_by_name = {
        name: global_value
        for name, global_value in globals_by_name.items()
        if name not in resident_global_names
    }
    duplicate_function_names = tuple(
        dict.fromkeys(policy.duplicate_functions)
    )
    source_inline_proxy_names = frozenset(
        set(resident_inline_proxy_names).intersection(functions)
    )
    forced_direct_dependency_names = tuple(
        dict.fromkeys(policy.direct_resident_dependencies)
    )
    invalid_module_defines = sorted(
        name
        for name, expression in policy.module_defines.items()
        if (
            not _C_MACRO_DECLARATOR.fullmatch(name)
            or not expression
            or len(expression) > 256
            or not _C_DEFINE_EXPRESSION.fullmatch(expression)
        )
    )
    if invalid_module_defines:
        raise GraphValidationError(
            "module defines must use safe object/function-like macro "
            "declarators and single-line constant expressions: "
            + ", ".join(invalid_module_defines)
        )
    if (
        policy.initialize_packed_dependencies_at_load
        and not policy.pack_resident_dependencies
    ):
        raise GraphValidationError(
            "load-time dependency initialization requires packed "
            "resident dependencies"
        )
    if (
        policy.bind_packed_dependencies_on_first_use
        and not policy.pack_resident_dependencies
    ):
        raise GraphValidationError(
            "first-use dependency binding requires packed resident "
            "dependencies"
        )
    if (
        policy.bind_packed_dependencies_on_first_use
        and policy.initialize_packed_dependencies_at_load
    ):
        raise GraphValidationError(
            "load-time initialization and first-use dependency binding "
            "are mutually exclusive"
        )
    if policy.autoload_alias is not None and not _MODULE_ALIAS.fullmatch(
        policy.autoload_alias
    ):
        raise GraphValidationError(
            "autoload alias must contain 1-64 modalias-safe characters"
        )
    resident_ro_after_init_names = tuple(
        dict.fromkeys(policy.resident_ro_after_init_globals)
    )
    invalid_ro_after_init_names = sorted(
        set(resident_ro_after_init_names) - set(resident_global_names)
    )
    if invalid_ro_after_init_names:
        raise GraphValidationError(
            "ro-after-init layout globals must be extracted resident "
            "globals: "
            + ", ".join(invalid_ro_after_init_names)
        )
    unsafe_ro_after_init_names = sorted(
        name
        for name in resident_ro_after_init_names
        if (
            not globals_by_name[name].has_initializer
            or "const" not in globals_by_name[name].type.split()
            or "__ro_after_init" in globals_by_name[name].macros
        )
    )
    if unsafe_ro_after_init_names:
        raise GraphValidationError(
            "ro-after-init layout requires initialized const globals not "
            "already placed there: "
            + ", ".join(unsafe_ro_after_init_names)
        )
    invalid_external_exports = sorted(
        symbol
        for symbol in external_resident_export_names
        if not _C_IDENTIFIER.fullmatch(symbol)
    )
    if invalid_external_exports:
        raise GraphValidationError(
            "external resident exports must be C identifiers: "
            + ", ".join(invalid_external_exports)
        )
    invalid_inline_proxies = sorted(
        symbol
        for symbol in resident_inline_proxy_names
        if not _C_IDENTIFIER.fullmatch(symbol)
    )
    if invalid_inline_proxies:
        raise GraphValidationError(
            "resident inline proxies must be C identifiers: "
            + ", ".join(invalid_inline_proxies)
        )
    if resident_inline_proxy_names and not policy.pack_resident_dependencies:
        raise GraphValidationError(
            "resident inline proxies require packed resident dependencies"
        )
    duplicate_inline_dependencies = sorted(
        set(resident_inline_proxy_names).intersection(
            set(resident_export_names).union(
                external_resident_export_names
            )
        )
    )
    if duplicate_inline_dependencies:
        raise GraphValidationError(
            "resident inline proxy is configured as another dependency: "
            + ", ".join(duplicate_inline_dependencies)
        )
    duplicate_exports = sorted(
        set(resident_export_names).intersection(
            external_resident_export_names
        )
    )
    if duplicate_exports:
        raise GraphValidationError(
            "resident export is configured twice: "
            + ", ".join(duplicate_exports)
        )
    unknown_forced_direct = sorted(
        set(forced_direct_dependency_names)
        - set(resident_export_names)
        - set(external_resident_export_names)
    )
    if unknown_forced_direct:
        raise GraphValidationError(
            "direct resident dependencies must also be declared as "
            "resident or external resident exports: "
            + ", ".join(unknown_forced_direct)
        )
    unknown_interfaces = sorted(set(interface_names) - set(functions))
    if unknown_interfaces:
        raise GraphValidationError(
            "interfaces missing from source extraction: "
            + ", ".join(unknown_interfaces)
        )
    if (
        policy.bind_packed_dependencies_on_first_use
        and len(
            {
                functions[name].source_path
                for name in interface_names
            }
        )
        != 1
    ):
        raise GraphValidationError(
            "first-use dependency binding requires every interface to "
            "share one resident translation unit"
        )
    unknown_exports = sorted(
        set(resident_export_names) - set(functions)
    )
    if unknown_exports:
        raise GraphValidationError(
            "resident exports missing from source extraction: "
            + ", ".join(unknown_exports)
        )
    unknown_duplicates = sorted(
        set(duplicate_function_names) - set(functions)
    )
    if unknown_duplicates:
        raise GraphValidationError(
            "duplicate functions missing from source extraction: "
            + ", ".join(unknown_duplicates)
        )
    overlap = sorted(
        set(interface_names).intersection(resident_export_names)
    )
    if overlap:
        raise GraphValidationError(
            "resident exports cannot also be module interfaces: "
            + ", ".join(overlap)
        )
    inline_proxy_interfaces = sorted(
        set(interface_names).intersection(source_inline_proxy_names)
    )
    if inline_proxy_interfaces:
        raise GraphValidationError(
            "resident inline proxies cannot also be module interfaces: "
            + ", ".join(inline_proxy_interfaces)
        )
    duplicate_overlap = sorted(
        set(duplicate_function_names).intersection(
            set(interface_names).union(resident_export_names)
        )
    )
    if duplicate_overlap:
        raise GraphValidationError(
            "duplicate functions cannot be interfaces or resident "
            "exports: "
            + ", ".join(duplicate_overlap)
        )
    for name in duplicate_function_names:
        function = functions[name]
        if function.storage != "static":
            raise GraphValidationError(
                f"{name}: only static functions can be duplicated"
            )
        unsafe_attributes = sorted(
            set(function.attributes).intersection(
                _UNSAFE_FUNCTION_ATTRIBUTES
            )
            - {"always_inline", "no_instrument_function"}
        )
        unsafe_macros = sorted(
            set(function.macros).intersection(_UNSAFE_FUNCTION_MACROS)
            - {"__always_inline", "notrace"}
        )
        if unsafe_attributes or unsafe_macros:
            markers = unsafe_attributes + unsafe_macros
            raise GraphValidationError(
                f"{name}: duplicated helper has unsafe marker(s): "
                + ", ".join(markers)
            )
        if function.variadic or function.has_unnamed_parameter:
            raise GraphValidationError(
                f"{name}: duplicated helper must have a complete "
                "non-variadic prototype"
            )
    preexisting_resident_exports = set()
    for name in resident_export_names:
        function = functions[name]
        unsafe_attributes = sorted(
            set(function.attributes).intersection(
                _UNSAFE_FUNCTION_ATTRIBUTES
            )
        )
        unsafe_macros = sorted(
            set(function.macros).intersection(_UNSAFE_FUNCTION_MACROS)
        )
        if (
            (unsafe_attributes or unsafe_macros)
            and not policy.pack_resident_dependencies
        ):
            markers = unsafe_attributes + unsafe_macros
            raise GraphValidationError(
                f"{name}: resident dependency has non-exportable "
                "marker(s): "
                + ", ".join(markers)
            )
        if function.variadic or function.has_unnamed_parameter:
            raise GraphValidationError(
                f"{name}: resident dependency must have a complete "
                "non-variadic prototype"
            )
        if (
            function.storage == "static"
            and _has_prior_static_declaration(function)
            and not policy.pack_resident_dependencies
        ):
            raise GraphValidationError(
                f"{name}: static resident dependency has a prior "
                "declaration that cannot be rewritten safely"
            )
        source = Path(function.source_path).read_text(encoding="utf-8")
        export_pattern = re.compile(
            r"\bEXPORT_SYMBOL(?:_GPL)?\s*\(\s*"
            + re.escape(name)
            + r"\s*\)"
        )
        if export_pattern.search(source):
            preexisting_resident_exports.add(name)
    moved_functions = {
        name: function
        for name, function in functions.items()
        if name not in resident_export_names
        and name not in duplicate_function_names
        and name not in source_inline_proxy_names
    }
    duplicated_functions = {
        name: functions[name] for name in duplicate_function_names
    }
    module_functions = {**moved_functions, **duplicated_functions}
    resident_function_entities = {
        name: functions[name]
        for name in dict.fromkeys(
            [*resident_export_names, *source_inline_proxy_names]
        )
    }
    dependency_names = tuple(
        dict.fromkeys(
            [
                *resident_export_names,
                *external_resident_export_names,
                *resident_inline_proxy_names,
            ]
        )
    )
    packed_dependency_kinds = (
        _classify_packed_dependencies(
            [
                *module_functions.values(),
                *moved_globals_by_name.values(),
            ],
            tuple(
                symbol
                for symbol in dependency_names
                if symbol not in forced_direct_dependency_names
            ),
        )
        if policy.pack_resident_dependencies
        else {}
    )
    if policy.pack_resident_dependencies and not dependency_names:
        raise GraphValidationError(
            "packed resident dependencies require at least one resident "
            "or external dependency"
        )
    if (
        policy.pack_resident_dependencies
        and dependency_names
        and not packed_dependency_kinds
    ):
        raise GraphValidationError(
            "packed resident dependencies have no movable AST reference: "
            + ", ".join(dependency_names)
        )
    initializer_dependencies = {
        reference.symbol
        for entity in moved_globals_by_name.values()
        for reference in entity.references
        if reference.symbol in packed_dependency_kinds
    }
    packed_initializer_trampolines = {
        symbol: functions[symbol]
        for symbol in sorted(initializer_dependencies)
        if symbol in resident_export_names
        and packed_dependency_kinds[symbol] == "function"
    }
    unpackable_initializer_dependencies = (
        initializer_dependencies
        - set(packed_initializer_trampolines)
    )
    if unpackable_initializer_dependencies:
        packed_dependency_kinds = {
            symbol: kind
            for symbol, kind in packed_dependency_kinds.items()
            if symbol not in unpackable_initializer_dependencies
        }
    if (
        policy.pack_resident_dependencies
        and dependency_names
        and not packed_dependency_kinds
    ):
        raise GraphValidationError(
            "packed dependencies occur only in constant initializers and "
            "lack extracted resident function signatures: "
            + ", ".join(sorted(unpackable_initializer_dependencies))
        )
    if packed_dependency_kinds:
        export_anchor = min(
            functions[name].source_path for name in interface_names
        )
        cross_unit_resident = sorted(
            name
            for name in resident_export_names
            if name in packed_dependency_kinds
            and functions[name].source_path != export_anchor
        )
        if cross_unit_resident:
            raise GraphValidationError(
                "packed source-local resident dependencies must share the "
                "interface translation unit: "
                + ", ".join(cross_unit_resident)
            )
    unpacked_static_resident_globals = sorted(
        name
        for name in dependency_resident_global_names
        if name not in packed_dependency_kinds
        and globals_by_name[name].storage == "static"
    )
    if unpacked_static_resident_globals:
        raise GraphValidationError(
            "source-local static resident globals require an exact packed "
            "dependency reference: "
            + ", ".join(unpacked_static_resident_globals)
        )
    for name in resident_export_names:
        if (
            name in packed_dependency_kinds
            or name in preexisting_resident_exports
        ):
            continue
        function = functions[name]
        unsafe_attributes = sorted(
            set(function.attributes).intersection(
                _UNSAFE_FUNCTION_ATTRIBUTES
            )
        )
        unsafe_macros = sorted(
            set(function.macros).intersection(_UNSAFE_FUNCTION_MACROS)
        )
        if unsafe_attributes or unsafe_macros:
            raise GraphValidationError(
                f"{name}: resident dependency has non-exportable "
                "marker(s): "
                + ", ".join(unsafe_attributes + unsafe_macros)
            )
        if (
            function.storage == "static"
            and _has_prior_static_declaration(function)
        ):
            raise GraphValidationError(
                f"{name}: static resident dependency has a prior "
                "declaration that cannot be rewritten safely"
            )

    for name in policy.failure_expressions:
        if name not in interface_names:
            raise GraphValidationError(
                f"failure expression provided for non-interface {name!r}"
            )
    for function in moved_functions.values():
        unsafe_attributes = sorted(
            set(function.attributes).intersection(
                _UNSAFE_FUNCTION_ATTRIBUTES
            )
        )
        if function.source_form == "syscall_define":
            # __do_sys_* is synthesized by SYSCALL_DEFINE and inherits this
            # marker from the architecture wrapper.  The generated ordinary
            # module implementation does not retain that wrapper attribute.
            unsafe_attributes = [
                attribute
                for attribute in unsafe_attributes
                if attribute != "no_instrument_function"
            ]
        unsafe_macros = sorted(
            set(function.macros).intersection(_UNSAFE_FUNCTION_MACROS)
        )
        if _is_static_inline(function):
            unsafe_attributes = [
                attribute
                for attribute in unsafe_attributes
                if attribute != "no_instrument_function"
            ]
            unsafe_macros = [
                macro for macro in unsafe_macros if macro != "notrace"
            ]
        if function.source_form == "syscall_define":
            # The syscall wrapper macro contributes notrace at the invocation
            # location; it is not present on the ordinary implementation
            # emitted into the module.
            unsafe_macros = [
                macro
                for macro in unsafe_macros
                if macro != "notrace"
            ]
        if unsafe_attributes or unsafe_macros:
            markers = unsafe_attributes + unsafe_macros
            raise GraphValidationError(
                f"{function.symbol}: source has non-movable marker(s): "
                + ", ".join(markers)
            )
        if function.variadic:
            raise GraphValidationError(
                f"{function.symbol}: variadic interfaces/implementations "
                "cannot be forwarded safely"
            )
        if function.has_unnamed_parameter:
            raise GraphValidationError(
                f"{function.symbol}: every parameter must have a name"
            )
    for global_value in moved_globals_by_name.values():
        if global_value.source_form == "macro_declaration_group":
            raise GraphValidationError(
                f"{global_value.symbol}: macro-generated declaration "
                "groups must remain resident until all co-definitions "
                "are modeled"
            )
        unsafe_attributes = sorted(
            set(global_value.attributes).intersection(
                _UNSAFE_GLOBAL_ATTRIBUTES
            )
        )
        unsafe_macros = sorted(
            set(global_value.macros).intersection(_UNSAFE_GLOBAL_MACROS)
        )
        pattern_markers = sorted(
            macro
            for macro in global_value.macros
            if "PER_CPU" in macro or "STATIC_KEY" in macro
        )
        markers = unsafe_attributes + unsafe_macros + pattern_markers
        if markers:
            raise GraphValidationError(
                f"{global_value.symbol}: global has non-movable marker(s): "
                + ", ".join(dict.fromkeys(markers))
            )
    for name in interface_names:
        _failure_statement(
            moved_functions[name],
            policy.failure_expressions,
        )

    rename = {
        symbol: f"linux_mod_impl_{_short_id(policy.module_name, symbol)}"
        for symbol in module_functions
    }
    header_relative = (
        f"include/linux/linux_modularizer/{module_object}_interface.h"
    )
    include_spelling = (
        f"linux/linux_modularizer/{module_object}_interface.h"
    )
    support_declarations, support_macros = _select_module_support(
        extraction,
        module_functions,
        resident_function_entities,
        globals_by_name,
    )
    _validate_interface_support_visibility(
        module_functions,
        interface_names,
        support_declarations,
    )

    module_include_entities: list[SourceEntity] = [
        *module_functions.values(),
        *resident_function_entities.values(),
        *moved_globals_by_name.values(),
        *(globals_by_name[name] for name in resident_global_names),
    ]
    (
        module_include_overrides,
        snapshotted_header_files,
        snapshotted_header_records,
    ) = _snapshot_external_quoted_headers(
        extraction,
        module_include_entities,
        policy,
        module_object,
    )

    source_replacements = _generate_resident_sources(
        extraction,
        functions,
        globals_by_name,
        interface_names,
        policy,
        include_spelling,
        resident_exports=frozenset(resident_export_names),
        external_resident_exports=external_resident_export_names,
        packed_dependency_kinds=packed_dependency_kinds,
        resident_globals=resident_global_names,
        duplicate_functions=frozenset(duplicate_function_names),
        resident_inline_proxies=source_inline_proxy_names,
        preexisting_resident_exports=frozenset(
            preexisting_resident_exports
        ),
    )
    module_source = _generate_module_source(
        extraction,
        module_functions,
        resident_function_entities,
        moved_globals_by_name,
        interface_names,
        rename,
        policy,
        include_spelling,
        packed_dependency_kinds=packed_dependency_kinds,
        resident_globals={
            name: globals_by_name[name]
            for name in resident_global_names
        },
        packed_initializer_trampolines=(
            packed_initializer_trampolines
        ),
        support_declarations=support_declarations,
        support_macros=support_macros,
        include_overrides=module_include_overrides,
    )
    header = _generate_interface_header(
        module_functions,
        interface_names,
        policy.module_name,
        bind_dependencies=(
            policy.bind_packed_dependencies_on_first_use
        ),
    )
    config_symbol = "LINUX_MODULARIZER_" + module_object.upper()
    source_directories = _source_directories(
        [*functions.values(), *globals_by_name.values()],
        policy.kernel_root,
    )
    makefile_lines = [
        f"obj-$(CONFIG_{config_symbol}) += {module_object}.o"
    ]
    makefile_lines.extend(
        f"ccflags-y += -I$(srctree)/{directory}"
        for directory in source_directories
        if directory != "."
    )
    if snapshotted_header_files:
        makefile_lines.append(
            f"CFLAGS_{module_object}.o += "
            "-I$(srctree)/include/linux/linux_modularizer/generated/"
            f"{module_object}"
        )
    files = {
        header_relative: header,
        f"kernel/linux_modularizer/{module_object}.c": module_source,
        "integration/Makefile.fragment": "\n".join(makefile_lines) + "\n",
        "integration/Kconfig.fragment": (
            f'config {config_symbol}\n'
            f'\ttristate "{policy.module_name} function module"\n'
            "\tdepends on MODULES\n"
            "\tdefault m\n"
            "\thelp\n"
            "\t  Generated function-level module. Keep this as m to retain\n"
            "\t  lazy loading through request_module().\n"
        ),
    }
    files.update(snapshotted_header_files)
    for source_path, content in source_replacements.items():
        relative = _resident_relative_path(
            source_path, policy.kernel_root
        )
        files[f"resident/{relative}"] = content
    manifest = _bundle_manifest(
        files,
        source_replacements,
        policy,
        module_object,
        config_symbol,
        packed_dependency_kinds=packed_dependency_kinds,
        packed_initializer_trampolines=(
            packed_initializer_trampolines
        ),
        preexisting_resident_exports=preexisting_resident_exports,
        resident_globals=set(resident_global_names),
        support_declarations=support_declarations,
        support_macros=support_macros,
        snapshotted_headers=snapshotted_header_records,
    )
    return GeneratedBundle(
        files=files,
        source_replacements=source_replacements,
        config_symbol=config_symbol,
        module_object=module_object,
        manifest=manifest,
    )


def _unique_symbols(
    entities: tuple[SourceEntity, ...], kind: str
) -> dict[str, SourceEntity]:
    result: dict[str, SourceEntity] = {}
    for entity in entities:
        if entity.symbol in result:
            raise GraphValidationError(
                f"ambiguous extracted {kind} symbol {entity.symbol!r}; "
                "generate one candidate per linkage-aware identity"
            )
        result[entity.symbol] = entity
    return result


def _classify_packed_dependencies(
    entities: list[SourceEntity],
    external_symbols: tuple[str, ...],
) -> dict[str, str]:
    """Classify audited external dependencies from exact AST references.

    The packed ABI rewrites only the recorded DeclRefExpr ranges. Requiring a
    unique function/global classification prevents broad textual macros from
    changing unrelated identifiers and makes every packed field auditable.
    """

    requested = set(external_symbols)
    kinds: dict[str, set[str]] = {symbol: set() for symbol in requested}
    for entity in entities:
        for reference in entity.references:
            if reference.symbol not in requested:
                continue
            if reference.kind not in {"function", "global"}:
                raise GraphValidationError(
                    f"packed dependency {reference.symbol!r} has "
                    f"unsupported AST reference kind {reference.kind!r}"
                )
            kinds[reference.symbol].add(reference.kind)
    ambiguous = sorted(
        symbol for symbol, values in kinds.items() if len(values) > 1
    )
    if ambiguous:
        raise GraphValidationError(
            "packed external dependencies have ambiguous AST kinds: "
            + ", ".join(ambiguous)
        )
    return {
        symbol: next(iter(kinds[symbol]))
        for symbol in sorted(kinds)
        if kinds[symbol]
    }


def _module_identifier(name: str) -> str:
    value = name.replace("-", "_")
    if not _C_IDENTIFIER.fullmatch(value):
        raise GraphValidationError(
            f"module_name must map to a C identifier, got {name!r}"
        )
    return value


